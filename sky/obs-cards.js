  bta: ["БТА", "Большой телескоп азимутальный", "САО РАН", "Архыз", "Специальная астрофизическая обсерватория"], pulkovo: ["Пулково", "Пулковская"],
  crao: ["КрАО", "Крымская", "Крымская обсерватория", "Научный"], gaish: ["ГАИШ", "МГУ", "Штернберга"], kazan: ["Казанская", "Энгельгардта", "Казань"],
  kourovka: ["Коуровка", "Коуровская"], sayan: ["Саянская", "Саянская обсерватория"], ussuri: ["Уссурийская", "Уссурийск"],
  keck: ["Кек", "Кека", "Keck", "Обсерватория Кек", "Мауна-Кеа"], lasilla: ["Ла Силья", "La Silla"], tololo: ["Серро Тололо", "Тололо", "Cerro Tololo"],
  paranal: ["Паранал", "VLT", "Очень большой телескоп"], teide: ["Тейде", "Teide"], greenwich: ["Гринвич", "Гринвичская"], effelsberg: ["Эффельсберг", "Effelsberg"],
  palomar: ["Паломар", "Palomar"], lick: ["Лик", "Ликская", "Лик обсерватория"], yerkes: ["Йеркс", "Йеркская", "Ерк", "Yerkes"], arecibo: ["Арекибо", "Arecibo"],
